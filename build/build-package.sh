#!/bin/bash
# =====================================================================
# build-package.sh - produce the macOS deployment artifacts.
#
# Outputs into dist/:
#   JumpCloudEnrollment-macOS.zip   the app (orchestrator + lib + user)
#   MDM-Command.sh                  paste into a JumpCloud command;
#                                   attach the zip alongside it
#   SHA256.txt                      the zip hash (pinned in the command)
#
# Build gates: LF line endings (CRLF breaks the macOS interpreter),
# bash syntax, and the unit tests must all pass.
# =====================================================================

set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIST="${ROOT}/dist"
ZIP_NAME="JumpCloudEnrollment-macOS.zip"
# Where the published zip lives. Baked into dist/MDM-Command.sh so the
# command is self-contained: --url https://... , or the PACKAGE_URL env var.
PACKAGE_URL="${PACKAGE_URL:-}"
while [[ $# -gt 0 ]]; do
    case "$1" in
        --url) PACKAGE_URL="$2"; shift 2 ;;
        *) shift ;;
    esac
done

fail() { printf 'BUILD FAILED: %s\n' "$*" >&2; exit 1; }

mkdir -p "$DIST"

# ---- Gate 1: no CRLF -------------------------------------------------
printf '==> Checking line endings\n'
CRLF_HITS="$(LC_ALL=C grep -rlI --include='*.sh' "$(printf '\r')" "$ROOT" 2>/dev/null \
    | grep -v "/dist/" || true)"
if [[ -n "$CRLF_HITS" ]]; then
    printf '%s\n' "$CRLF_HITS" | sed 's/^/  CRLF: /'
    fail "CRLF line endings found (they break /bin/bash on macOS)"
fi
printf '    all shell scripts are LF\n'

# ---- Gate 2: syntax --------------------------------------------------
printf '==> Syntax checking\n'
for f in "$ROOT"/jc-enroll.sh "$ROOT"/lib/*.sh "$ROOT"/user/*.sh "$ROOT"/tests/*.sh; do
    bash -n "$f" || fail "syntax error in $f"
done
printf '    ok\n'

# ---- Gate 3: unit tests ----------------------------------------------
printf '==> Unit tests\n'
bash "$ROOT/tests/test-units.sh" >/tmp/jc_units.log 2>&1 || {
    tail -20 /tmp/jc_units.log; fail "unit tests failed"
}
tail -1 /tmp/jc_units.log | sed 's/^/    /'

printf '==> Flow tests (state machine)\n'
bash "$ROOT/tests/test-flow.sh" >/tmp/jc_flow.log 2>&1 || {
    tail -25 /tmp/jc_flow.log; fail "flow tests failed"
}
tail -1 /tmp/jc_flow.log | sed 's/^/    /'

# ---- Package ---------------------------------------------------------
printf '==> Packaging\n'
rm -f "${DIST}/${ZIP_NAME}"
# Uses `zip`, which ships with macOS, and preserves the on-disk modes -
# so the exec bits are set here first. (No python: macOS has none.)
command -v zip >/dev/null 2>&1 || fail "the 'zip' tool is required"
(
    cd "$ROOT" || exit 1
    chmod 755 jc-enroll.sh 2>/dev/null || true
    chmod 755 lib/*.sh user/*.sh 2>/dev/null || true
    chmod 644 lib/*.js 2>/dev/null || true

    PACK=("jc-enroll.sh")
    for d in lib user vendor; do          # vendor/ is optional
        [[ -d "$d" ]] && PACK+=("$d")
    done
    zip -q -r -X "${DIST}/${ZIP_NAME}" "${PACK[@]}" \
        -x '*/.DS_Store' '*/._*'
) || fail "packaging failed"
printf '    entries: %s\n' "$(unzip -Z1 "${DIST}/${ZIP_NAME}" 2>/dev/null | wc -l | tr -d ' ')"

if command -v shasum >/dev/null 2>&1; then
    ZIP_SHA="$(shasum -a 256 "${DIST}/${ZIP_NAME}" | awk '{print $1}')"
else
    ZIP_SHA="$(sha256sum "${DIST}/${ZIP_NAME}" | awk '{print $1}')"
fi
printf '%s  %s\n' "$ZIP_SHA" "$ZIP_NAME" > "${DIST}/SHA256.txt"
printf '    %s (%s bytes)\n' "$ZIP_NAME" "$(wc -c < "${DIST}/${ZIP_NAME}" | tr -d ' ')"
printf '    sha256 %s\n' "$ZIP_SHA"

# ---- MDM command -----------------------------------------------------
printf '==> Generating MDM-Command.sh\n'
cat > "${DIST}/MDM-Command.sh" <<'COMMAND'
#!/bin/bash
# =====================================================================
# JumpCloud macOS device enrollment - MDM command.
# Generated by build/build-package.sh - DO NOT EDIT the logic below.
#
# ONE command, ONE zip. Paste this whole file into a JumpCloud command;
# it fetches the package, checks it against the SHA-256 pinned below, and
# runs it. Nothing else is deployed to the Mac.
#
# JumpCloud console setup:
#   - Command type: Mac (bash), Run As: root
#   - Timeout: at least 3900 seconds (the user interacts with a window)
#   - Set PACKAGE_URL below to the published zip, OR attach the zip to
#     the command instead (JumpCloud puts attachments in /tmp on macOS).
#     An attached copy is used in preference to downloading.
#
# The download is safe because the hash is pinned HERE, in the text you
# paste into the console: a package that does not match is refused and
# never executed. Re-run build-package.sh and re-paste this command
# whenever the zip changes, or the hash check will (correctly) fail.
#
# The bare template assignments below are intentional: JumpCloud
# substitutes them at dispatch and supplies its own quoting.
# =====================================================================
set -uo pipefail

API_KEY={{Apikey}}
JC_ORG_VAR={{OrgID}}
SYSTEM_ID={{device.id}}
PRIMARY_USER_ID={{device.primary_user_id}}

# ================= TENANT SETTINGS - EDIT THESE =================
# Everything an organization changes lives HERE, not in the package.
ORG_ID=""                              # JumpCloud Org ID (required if
                                       # the OrgID variable is not set)
JC_REGION="US"                         # US or EU tenant
COMPANY_NAME="Your Organization"
SUPPORT_CONTACT="your IT administrator"
LOGO_PATH=""                           # optional logo PNG on the device
DEFER_MINUTES=120                      # "Remind Me Later" snooze
DEFER_MAX_COUNT=0                      # 0 = unlimited defers
LDAP_HOST="ldap.jumpcloud.com"         # rarely changed
LDAP_PORT=636                          # 636 = LDAPS, 389 = StartTLS
REQUIRE_SECURE_TOKEN=1                 # gate on the JC service account
SHOW_BLOCKED_SCREEN=0                  # 1 = tell the user when blocked
PACKAGE_URL="__PKGURL__"               # https:// URL of the zip. Leave
                                       # empty to require an attachment.
# ================================================================

ZIP_SHA256="__ZIPSHA__"
ZIP_NAME="JumpCloudEnrollment-macOS.zip"
APP_DIR="/Library/Application Support/JumpCloudEnrollment/app"

# Unsubstituted template variables would arrive as literal braces. The
# marker is assembled at runtime so this file never contains a stray
# double-brace, which a template validator can reject.
TPL='{'; TPL="${TPL}{"
case "${API_KEY}" in *"$TPL"*) echo "Status: RequiresAction | Issue: run via a JumpCloud command"; exit 1 ;; esac
case "${JC_ORG_VAR}" in *"$TPL"*) JC_ORG_VAR="" ;; esac
case "${PRIMARY_USER_ID}" in *"$TPL"*) PRIMARY_USER_ID="" ;; esac
case "${SYSTEM_ID}" in *"$TPL"*) echo "Status: RequiresAction | Issue: device id not substituted"; exit 1 ;; esac

# The OrgID automation variable wins only when the tenant block is blank.
[[ -z "${ORG_ID}" && -n "${JC_ORG_VAR}" ]] && ORG_ID="${JC_ORG_VAR}"
if [[ -z "${ORG_ID}" ]]; then
    echo "Status: RequiresAction | Issue: ORG_ID not set (edit TENANT SETTINGS)"
    exit 1
fi

# ---- Find the package: attachment first, then download --------------
ZIP=""
for c in "/tmp/${ZIP_NAME}" "/var/tmp/${ZIP_NAME}" "$(dirname "$0")/${ZIP_NAME}"; do
    [[ -f "$c" ]] && { ZIP="$c"; break; }
done

DOWNLOADED=""
if [[ -z "$ZIP" && -n "$PACKAGE_URL" ]]; then
    # Assembled at runtime so the build's own substitution cannot rewrite
    # this guard along with the setting it is guarding.
    PKG_PLACEHOLDER="__PKG"; PKG_PLACEHOLDER="${PKG_PLACEHOLDER}URL__"
    case "$PACKAGE_URL" in
        "$PKG_PLACEHOLDER")
            echo "Status: RequiresAction | Issue: PACKAGE_URL not set (edit TENANT SETTINGS)"
            exit 1 ;;
        https://*) ;;
        *)
            # The package is executed as root; refuse anything but TLS.
            echo "Status: RequiresAction | Issue: PACKAGE_URL must be https://"
            exit 1 ;;
    esac
    DOWNLOADED="$(mktemp "/private/tmp/${ZIP_NAME}.XXXXXX")"
    chmod 600 "$DOWNLOADED"
    ok=0
    for attempt in 1 2 3; do
        if curl -fsSL --proto '=https' --tlsv1.2 \
                --connect-timeout 20 --max-time 180 \
                -o "$DOWNLOADED" "$PACKAGE_URL"; then
            ok=1
            break
        fi
        echo "Download attempt ${attempt} failed; retrying..."
        sleep 5
    done
    if [[ $ok -ne 1 ]]; then
        rm -f "$DOWNLOADED"
        echo "Status: RequiresAction | Issue: could not download the package"
        exit 1
    fi
    ZIP="$DOWNLOADED"
    echo "Package downloaded."
fi

if [[ -z "$ZIP" ]]; then
    echo "Status: RequiresAction | Issue: ${ZIP_NAME} not found (set PACKAGE_URL or attach the zip)"
    exit 1
fi

# ---- Verify the package before running it as root -------------------
# The pin lives in this command, not in the package, so a tampered or
# stale download is refused rather than executed.
ACTUAL="$(shasum -a 256 "$ZIP" | awk '{print $1}')"
if [[ "$ACTUAL" != "$ZIP_SHA256" ]]; then
    [[ -n "$DOWNLOADED" ]] && rm -f "$DOWNLOADED"
    echo "Status: RequiresAction | Issue: package hash mismatch"
    echo "Expected ${ZIP_SHA256} got ${ACTUAL}"
    exit 1
fi
echo "Package hash verified."

# ---- Stage and run ---------------------------------------------------
rm -rf "$APP_DIR"
mkdir -p "$APP_DIR"
if ! unzip -o -q "$ZIP" -d "$APP_DIR"; then
    [[ -n "$DOWNLOADED" ]] && rm -f "$DOWNLOADED"
    echo "Status: RequiresAction | Issue: could not extract package"
    exit 1
fi
chmod +x "$APP_DIR/jc-enroll.sh" "$APP_DIR/user/"*.sh 2>/dev/null || true
[[ -n "$DOWNLOADED" ]] && rm -f "$DOWNLOADED"

export API_KEY ORG_ID SYSTEM_ID PRIMARY_USER_ID JC_REGION
export COMPANY_NAME SUPPORT_CONTACT LOGO_PATH
export DEFER_MINUTES DEFER_MAX_COUNT
export LDAP_HOST LDAP_PORT REQUIRE_SECURE_TOKEN SHOW_BLOCKED_SCREEN

exec "$APP_DIR/jc-enroll.sh"
COMMAND

sed -e "s/__ZIPSHA__/${ZIP_SHA}/g" -e "s|__PKGURL__|${PACKAGE_URL}|g" "${DIST}/MDM-Command.sh" > "${DIST}/MDM-Command.sh.tmp" \
    && mv "${DIST}/MDM-Command.sh.tmp" "${DIST}/MDM-Command.sh"
chmod +x "${DIST}/MDM-Command.sh" 2>/dev/null || true
printf '    %s\n' "${DIST}/MDM-Command.sh"

printf '\nBuild complete. Artifacts in dist/\n'
